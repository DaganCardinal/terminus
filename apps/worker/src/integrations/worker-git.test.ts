const encoder = new TextEncoder()
function concat(...chunks: Uint8Array[]): Uint8Array<ArrayBuffer> {
  const joined = new Uint8Array(
    chunks.reduce((size, chunk) => size + chunk.length, 0)
  )
  let at = 0
  for (const chunk of chunks) {
    joined.set(chunk, at)
    at += chunk.length
  }
  return joined
}
function packet(value: string | Uint8Array) {
  const bytes = typeof value === "string" ? encoder.encode(value) : value
  return concat(
    encoder.encode((bytes.length + 4).toString(16).padStart(4, "0")),
    bytes
  )
}
const flush = encoder.encode("0000")

describe("Worker Git promotion", () => {
  it("clones a native Git pack and pushes from the Worker filesystem, cleaning up afterwards", async () => {
    let head = baseline
    const send = vi.fn<typeof fetch>(async (url, init) => {
      const requested = new URL(String(url))
      const service = requested.searchParams.get("service")
      const isSource = requested.pathname.startsWith("/source.git/")
      expect(new Headers(init?.headers).get("authorization")).toBe(
        `Bearer ${isSource ? source.token : target.token}`
      )
      expect(init?.redirect).toBe("manual")
      if (service)
        return new Response(
          concat(
            packet(`# service=${service}\n`),
            flush,
            packet(
              `${isSource ? accepted : head} HEAD\0report-status side-band-64k ofs-delta symref=HEAD:refs/heads/main\n`
            ),
            packet(`${isSource ? accepted : head} refs/heads/main\n`),
            flush
          ),
          {
            headers: {
              "content-type": `application/x-${service}-advertisement`,
            },
          }
        )
      if (requested.pathname.endsWith("git-upload-pack"))
        return new Response(
          concat(packet("NAK\n"), packet(concat(Uint8Array.of(1), pack)), flush)
        )
      expect(requested.pathname).toBe("/target.git/git-receive-pack")
      expect(new TextDecoder().decode(init?.body as Uint8Array)).toContain(
        `${baseline} ${accepted} refs/heads/main`
      )
      head = accepted
      return new Response(
        concat(
          packet(
            concat(
              Uint8Array.of(1),
              packet("unpack ok\n"),
              packet("ok refs/heads/main\n"),
              flush
            )
          ),
          flush
        )
      )
    })
    const before = await readdir("/tmp")
    const promote = workerGitPromotion(async () => head, send)
    const input = { source, target, fromCommit: baseline, toCommit: accepted }
    await promote(input)
    expect(head).toBe(accepted)
    expect(send).toHaveBeenCalledTimes(4)
    expect(await readdir("/tmp")).toEqual(before)
    await promote(input)
    expect(send).toHaveBeenCalledTimes(4)
    expect(await readdir("/tmp")).toEqual(before)
  })

  it("never sends tokens to ungranted endpoints or write requests to the source", async () => {
    const send = vi.fn<typeof fetch>()
    const http = promotionHttp([source, target], send)
    for (const url of [
      "https://elsewhere.test/target.git/info/refs?service=git-upload-pack",
      `${source.remote}/info/refs?service=git-receive-pack`,
      `${source.remote}/git-receive-pack`,
      `${target.remote}/objects/HEAD`,
      "https://user:password@artifacts.test/target.git/info/refs?service=git-upload-pack",
    ])
      await expect(
        http.request({
          url,
          method: url.endsWith("git-receive-pack") ? "POST" : "GET",
        })
      ).rejects.toThrow("outside the promotion grants")
    expect(send).not.toHaveBeenCalled()
  })

  it("refuses redirects and cancels oversized downloads, including chunked ones", async () => {
    const cancelled = vi.fn()
    const response = () =>
      new ReadableStream<Uint8Array>({
        start(controller) {
          controller.enqueue(new Uint8Array(5))
        },
        cancel: cancelled,
      })
    const send = vi.fn<typeof fetch>()
    const http = promotionHttp([source, target], send, 4)
    const request = {
      url: `${source.remote}/info/refs?service=git-upload-pack`,
    }
    send.mockResolvedValueOnce(
      new Response(response(), {
        status: 302,
        headers: { location: "https://elsewhere.test/" },
      })
    )
    await expect(http.request(request)).rejects.toThrow("302")
    send.mockResolvedValueOnce(
      new Response(response(), { headers: { "content-length": "5" } })
    )
    await expect(http.request(request)).rejects.toBeInstanceOf(GitCapacityError)
    send.mockResolvedValueOnce(new Response(response()))
    const download = await http.request(request)
    await expect(download.body!.next()).rejects.toBeInstanceOf(GitCapacityError)
    expect(cancelled).toHaveBeenCalledTimes(3)
  })
})
